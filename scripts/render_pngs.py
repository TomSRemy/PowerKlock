#!/usr/bin/env python3
"""PNG image of every catalogue chart, for mails, chat tools and other apps.

Serves the site locally, opens index.html?embed=<chart> for each chart of
the catalogue (default parameters) in headless Chromium and saves a
1200 × 630 screenshot to <out>/<chart>.png, plus <out>/charts.json (the
catalogue: id, title, description, parameters, PNG and embed URLs).
The workflow publishes <out> on the `png` branch, replaced each time.

    pip install playwright && python -m playwright install chromium
    python scripts/render_pngs.py out_png
"""
import functools
import http.server
import json
import os
import sys
import threading
from datetime import datetime, timezone

from playwright.sync_api import sync_playwright

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
PORT = 8811
SITE = 'https://tomsremy.github.io/PowerKlock/'
RAW = 'https://raw.githubusercontent.com/TomSRemy/PowerKlock/png/'


def serve():
    class Quiet(http.server.SimpleHTTPRequestHandler):
        def log_message(self, *a):
            pass
    srv = http.server.ThreadingHTTPServer(('127.0.0.1', PORT), functools.partial(Quiet, directory=ROOT))
    threading.Thread(target=srv.serve_forever, daemon=True).start()
    return srv


def main():
    out = sys.argv[1] if len(sys.argv) > 1 else 'out_png'
    os.makedirs(out, exist_ok=True)
    srv = serve()
    done, failed = [], []
    with sync_playwright() as pw:
        b = pw.chromium.launch()
        p = b.new_page(viewport={'width': 1200, 'height': 630}, device_scale_factor=1.5)
        p.goto(f'http://127.0.0.1:{PORT}/index.html')
        p.wait_for_timeout(4000)
        cat = p.evaluate("""PKW.list().map(w => ({ id: w.id, title: w.title, desc: w.desc, kind: w.kind, source: w.source, category: w.category,
            params: (w.params || []).map(d => ({ key: d.key, label: d.label, options: d.options.map(o => o[0]) })), defaults: w.defaults || {} }))""")
        for w in cat:
            try:
                p.goto(f'http://127.0.0.1:{PORT}/index.html?embed={w["id"]}')
                p.wait_for_function('document.body.dataset.embedReady', timeout=45000)
                p.wait_for_timeout(1200)
                state = p.evaluate('document.body.dataset.embedReady')
                p.screenshot(path=os.path.join(out, w['id'] + '.png'))
                (done if state == '1' else failed).append(w['id'])
            except Exception as e:
                failed.append(w['id'])
                print(f'::warning::{w["id"]}: {str(e)[:120]}')
        b.close()
    srv.shutdown()
    for w in cat:
        w['png'] = RAW + w['id'] + '.png' if w['id'] in done else None
        w['embed'] = SITE + 'index.html?embed=' + w['id']
    with open(os.path.join(out, 'charts.json'), 'w') as f:
        json.dump({'updated': datetime.now(timezone.utc).strftime('%Y-%m-%dT%H:%M:%SZ'), 'charts': cat}, f, ensure_ascii=False, indent=1)
    with open(os.path.join(out, 'README.md'), 'w') as f:
        f.write('# PowerKlock chart images\n\nGenerated by `scripts/render_pngs.py` (workflow *Render chart images*); this branch is replaced at each run.\nList: `charts.json`. Image of a chart: `<chart id>.png`.\n')
    print(f'{len(done)} images, {len(failed)} failed: {", ".join(failed)}')
    return 0


if __name__ == '__main__':
    sys.exit(main())
